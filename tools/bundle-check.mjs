// Check the design bundle in bundle/project/ against the Design System artifact format, and render
// every preview as the page does: in a frame that has loaded tokens.css, components/bundle.css,
// the libraries and components/bundle.js, in light and dark, with the network shut.
//
// Usage:  npm run bundle:check [-- --shots <folder>]
//
// Prints one line per check: ok or FAIL with what failed. Exits 1 on any failure. With --shots,
// writes a screenshot of each preview in each theme to that folder.

import { chromium } from 'playwright';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { load } from './load.mjs';
import { ALIAS, COLOR, LENGTH, NAME, OTHER, compileTokens, frameDocument, otherFamilies } from './ds-frame.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'bundle', 'project');
const FRAMES = path.join(ROOT, 'bundle', 'frames');
const shotsAt = process.argv.indexOf('--shots');
const SHOTS = shotsAt > -1 ? path.resolve(process.argv[shotsAt + 1]) : null;
if (!existsSync(path.join(DIR, 'design-system.json'))) { console.error('No bundle: run npm run bundle first.'); process.exit(2); }

let failed = false;
const report = (name, problems) => {
  const list = problems.filter(Boolean);
  console.log(`${list.length ? 'FAIL' : 'ok  '}  ${name}`);
  for (const p of list.slice(0, 12)) console.log(`        ${p}`);
  if (list.length > 12) console.log(`        and ${list.length - 12} more`);
  if (list.length) failed = true;
};
const read = p => readFileSync(path.join(DIR, p), 'utf8');
const json = p => JSON.parse(read(p));

// ---------- files ----------

const all = [];
const walk = d => { for (const e of readdirSync(path.join(DIR, d), { withFileTypes: true })) { const p = d ? `${d}/${e.name}` : e.name; if (e.isDirectory()) walk(p); else all.push(p); } };
walk('');
const files = all.filter(p => p !== 'design-system.json');
const size = p => statSync(path.join(DIR, p)).size;
const KB = 1024, MB = 1024 * KB;
const capOf = p => (p === 'README.md' ? 200 * KB : p === 'tokens.json' ? 512 * KB : /^components\/[^/]+\/preview\.html$/.test(p) ? 256 * KB
  : /^components\/[^/]+\/README\.md$/.test(p) ? 64 * KB : p === 'components/bundle.js' ? 6 * MB : p === 'components/bundle.css' ? 2 * MB
    : /^components\/lib\//.test(p) ? 2 * MB : /^fonts\//.test(p) ? MB : 512 * KB);
const REFUSED = /(^|\/)(package\.json|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|bunfig\.toml|tsconfig\.json|deno\.jsonc?|CLAUDE\.md|AGENTS\.md)$/;
report(`files: ${files.length} under project/ (1008 at most), ${(files.reduce((n, p) => n + size(p), 0) / KB).toFixed(0)} KB`, [
  files.length > 1008 && `${files.length} files`,
  ...files.map(p => {
    if (p.split('/').some(s => s.startsWith('.') || s === 'node_modules')) return `${p}: a dot segment or node_modules`;
    if (REFUSED.test(p) || /^(index\.html|SKILL\.md|artifact-type\/)/.test(p) || /~\d/.test(p)) return `${p}: a refused path`;
    if (/^(api\/|manifest\.json$)/.test(p)) return `${p}: generated by the page`;
    if (/^components\/([^/]+)\//.test(p) && !/^[A-Za-z_$][\w$]*$/.test(p.split('/')[1])) return `${p}: component folder is not a JS identifier`;
    if (size(p) > capOf(p)) return `${p}: ${size(p)} bytes, over ${capOf(p)}`;
    return null;
  }),
]);

// ---------- the index ----------

const index = json('design-system.json');
const iso = s => typeof s === 'string' && !Number.isNaN(Date.parse(s)) && /^\d{4}-\d\d-\d\dT/.test(s);
const lc = index.lastChange || {};
report('design-system.json', [
  index.v !== 3 && 'v is not 3', index.layout !== 'files' && 'layout is not "files"',
  !(index.createdOnFiles && index.createdOnFiles.v === 1 && iso(index.createdOnFiles.at)) && 'createdOnFiles is not {v:1, at}',
  index.title !== 'Content Morphia' && `title is ${JSON.stringify(index.title)}`,
  !/^[A-Za-z_$][\w$]*$/.test(index.namespace || '') && 'namespace is not a JS identifier',
  ...['sections', 'assetGroups', 'blobs'].map(k => (index[k] && typeof index[k] === 'object' && !Array.isArray(index[k]) ? null : `${k} is not an object`)),
  !Array.isArray(index.groups) && 'groups is not a list', !(index.docs && Array.isArray(index.docs.sections)) && 'docs.sections is not a list',
  !Array.isArray(index.libraries) && 'libraries is not a list',
  ...(index.libraries || []).map(l => (['name', 'version', 'global', 'file'].every(k => typeof l[k] === 'string') && existsSync(path.join(DIR, l.file)) ? null : `library ${JSON.stringify(l)} is incomplete or missing its file`)),
  !(typeof lc.by === 'string' && lc.by && lc.by.length <= 200) && 'lastChange.by', !iso(lc.at) && 'lastChange.at',
  lc.via !== undefined && !(typeof lc.via === 'string' && lc.via.length <= 120) && 'lastChange.via', lc.note !== undefined && !(typeof lc.note === 'string' && lc.note.length <= 280 && !/\n/.test(lc.note)) && 'lastChange.note',
  index.editing !== undefined && !['code', 'off'].includes(index.editing) && 'editing is not "code" or "off"',
]);

// ---------- tokens.json ----------

const t = json('tokens.json');
const problems = [];
const themes = (t.color && t.color.themes) || [];
const themeIds = themes.map(x => x.id);
if (!themes.length || themes.length > 8) problems.push('color.themes: 1 to 8 themes');
const nonType = new Map();
const named = (family, x) => {
  if (!NAME.test(x.name)) problems.push(`${family} ${x.name}: name`);
  if (nonType.has(x.name)) problems.push(`${family} ${x.name}: name also in ${nonType.get(x.name)}`);
  nonType.set(x.name, family);
  if (!x.usage) problems.push(`${family} ${x.name}: no usage note`);
  else if (x.usage.length > 1000) problems.push(`${family} ${x.name}: usage over 1000 characters`);
};
const perTheme = (x, ok, family) => {
  const v = typeof x.value === 'string' ? { [themeIds[0]]: x.value } : x.value;
  if (!v || typeof v !== 'object') return problems.push(`${family} ${x.name}: value`);
  for (const [id, val] of Object.entries(v)) {
    if (!themeIds.includes(id)) problems.push(`${family} ${x.name}: unknown theme ${id}`);
    if (!ok(val)) problems.push(`${family} ${x.name}: ${id} value ${val}`);
  }
};
const colors = t.color.tokens;
if (colors.length > 600) problems.push('over 600 colours');
for (const c of colors) { named('color', c); perTheme(c, v => COLOR.test(v) || ALIAS.test(v), 'color'); }
const colorNames = new Set(colors.map(c => c.name));
for (const c of colors) for (const v of Object.values(typeof c.value === 'string' ? { x: c.value } : c.value)) {
  const a = (ALIAS.exec(v) || [])[1];
  if (a && (!colorNames.has(a) || a === c.name)) problems.push(`color ${c.name}: alias of ${a}`);
}
for (const k of ['spacing', 'radius']) for (const x of (t[k] && t[k].tokens) || []) { named(k, x); if (!LENGTH.test(String(x.value)) && typeof x.value !== 'number') problems.push(`${k} ${x.name}: ${x.value}`); }
for (const x of (t.shadow && t.shadow.tokens) || []) { named('shadow', x); perTheme(x, v => typeof v === 'string' && v.length <= 400 && !/var\(|url\(/.test(v), 'shadow'); }
const others = otherFamilies(t);
if (others.length > 12) problems.push('over 12 further families');
for (const k of others) {
  if (t[k].tokens.length > 60) problems.push(`${k}: over 60 tokens`);
  for (const x of t[k].tokens) { named(k, x); if (!OTHER.test(String(x.value)) || /url\(|var\(/.test(x.value)) problems.push(`${k} ${x.name}: ${x.value}`); }
}
for (const k of ['spacing', 'radius', 'shadow', ...others]) if (t[k] && t[k].note && t[k].note.length > 400) problems.push(`${k}: note over 400 characters`);
const ty = t.type;
const fams = Object.entries(ty.families || {});
if (fams.length > 12) problems.push('over 12 type families');
for (const [k, v] of fams) if (!NAME.test(k) || v.length > 200 || /[;{}<>\\()]/.test(v) || (v.match(/'/g) || []).length % 2 || (v.match(/"/g) || []).length % 2) problems.push(`type family ${k}: ${v}`);
for (const f of ty.fonts) {
  if (!f.family || /["']/.test(f.family)) problems.push(`font ${f.family}: family`);
  if (!existsSync(path.join(DIR, f.file))) problems.push(`font ${f.file}: no such file`);
  else if (readFileSync(path.join(DIR, f.file)).subarray(0, 4).toString('latin1') !== 'wOF2') problems.push(`font ${f.file}: not WOFF2`);
  if (!/^\d{1,4}( \d{1,4})?$/.test(String(f.weight)) || !['normal', 'italic', 'oblique'].includes(f.style)) problems.push(`font ${f.file}: weight or style`);
}
const listed = new Set(ty.fonts.map(f => f.file));
for (const p of files.filter(p => p.startsWith('fonts/'))) if (!listed.has(p)) problems.push(`${p}: not listed in type.fonts`);
const styleNames = new Set();
if (ty.groups.length > 12) problems.push('over 12 type groups');
if (ty.groups.flatMap(g => g.styles).length > 80) problems.push('over 80 type styles');
for (const g of ty.groups) {
  if (!ty.families[g.family]) problems.push(`type group ${g.name}: family ${g.family}`);
  for (const s of g.styles) {
    if (!NAME.test(s.name) || styleNames.has(s.name)) problems.push(`type style ${s.name}: name`);
    styleNames.add(s.name);
    if (!LENGTH.test(s.fontSize)) problems.push(`type style ${s.name}: fontSize ${s.fontSize}`);
    if (s.lineHeight !== undefined && !(LENGTH.test(s.lineHeight) || (/^\d*\.?\d+$/.test(s.lineHeight) && +s.lineHeight < 10))) problems.push(`type style ${s.name}: lineHeight ${s.lineHeight}`);
    if (!(+s.fontWeight >= 1 && +s.fontWeight <= 1000)) problems.push(`type style ${s.name}: fontWeight ${s.fontWeight}`);
    if (s.letterSpacing !== undefined && !LENGTH.test(s.letterSpacing) && !/^-?\d*\.?\d+(px|em|rem)$/.test(s.letterSpacing)) problems.push(`type style ${s.name}: letterSpacing ${s.letterSpacing}`);
    if (!s.usage) problems.push(`type style ${s.name}: no usage note`);
    if (s.sample && s.sample.length > 200) problems.push(`type style ${s.name}: sample over 200 characters`);
  }
}
report(`tokens.json: ${colors.length} colours in ${themes.length} themes, ${ty.groups.flatMap(g => g.styles).length} type styles, ${ty.fonts.length} fonts, ${['spacing', 'radius', 'shadow', ...others].map(k => `${t[k].tokens.length} ${k}`).join(', ')}`, problems);
report('tokens.css: as the page compiles tokens.json', [read('tokens.css') !== compileTokens(t, index.title) && 'tokens.css differs from the compiled tokens.json']);

// ---------- bundle.js, bundle.css, libraries, components ----------

const js = read('components/bundle.js');
const head = (js.split('\n')[0].match(/^\/\* @ds-bundle: (\{.*\}) \*\/$/) || [])[1];
const header = head ? JSON.parse(head) : null;
const folders = readdirSync(path.join(DIR, 'components'), { withFileTypes: true }).filter(e => e.isDirectory() && e.name !== 'lib').map(e => e.name);
const comps = header ? header.components.map(c => c.name) : [];
report(`components/bundle.js: ${comps.length} components in its header`, [
  !header && 'line 1 is not a @ds-bundle header',
  header && header.format !== 4 && 'header format is not 4', header && header.namespace !== index.namespace && 'header namespace differs from the index',
  /<\/script|<!--/i.test(js) && 'bundle.js holds </script or <!--',
  /<\/style/i.test(read('components/bundle.css')) && 'bundle.css holds </style',
  ...(index.libraries || []).map(l => (/<\/script|<!--/i.test(read(l.file)) ? `${l.file} holds </script or <!--` : null)),
  comps.includes('Cover') && 'Cover is in the header',
  ...comps.map(c => (existsSync(path.join(DIR, 'components', c, 'preview.html')) && existsSync(path.join(DIR, 'components', c, 'README.md')) ? null : `${c}: no preview.html or README.md`)),
  ...folders.filter(f => f !== 'Cover' && !comps.includes(f)).map(f => `components/${f}: not in the header`),
  readdirSync(path.join(DIR, 'components', 'Cover')).join(',') !== 'preview.html' && 'components/Cover holds more than preview.html',
]);

const MARKER = /^<!-- @dsCard((?: (?:group|subtitle)="[^"]*"| (?:height|width)=\d+| floor(?:=static)?| page)*) -->$/;
const previews = [...comps, 'Cover'].map(c => `components/${c}/preview.html`);
report(`previews: ${previews.length}, marker on line 1, nothing that loads from outside`, previews.flatMap(p => {
  const text = read(p);
  const line = text.split('\n')[0];
  const h = +((line.match(/height=(\d+)/) || [])[1]);
  return [
    !MARKER.test(line) && `${p}: line 1 is not a @dsCard marker`,
    !(h >= 40 && h <= 4000) && `${p}: height ${h}`,
    p.includes('/Cover/') && !(h >= 240 && h <= 360) && `${p}: cover height ${h} is outside 240 to 360`,
    /<(iframe|frame|object|embed|portal|noscript)\b/i.test(text) && `${p}: a refused element`,
    /\s(src|href)="(?!#|data:)[^"]+"/.test(text.replace(/<a\b[^>]*>/g, '')) && `${p}: loads a file`,
    /url\(\s*["']?(?!data:)[^)"'\s]/.test(text) && `${p}: a url() outside data:`,
  ];
}));

const mdFiles = files.filter(p => /\.md$/.test(p));
report(`README files: ${mdFiles.length}, no title on README.md, no en or em dash outside code`, [
  /^# /.test(read('README.md')) && 'README.md starts with a title',
  ...mdFiles.map(p => {
    const prose = read(p).replace(/```[\s\S]*?```/g, '').replace(/`[^`\n]*`/g, '');
    const n = (prose.match(/[–—]/g) || []).length;
    return n ? `${p}: ${n} dashes` : null;
  }),
]);

// ---------- rendering ----------

mkdirSync(FRAMES, { recursive: true });
if (SHOTS) mkdirSync(SHOTS, { recursive: true });
const browser = await chromium.launch();
const render = [];
for (const p of previews) {
  const comp = p.split('/')[1];
  const marker = +read(p).split('\n')[0].match(/height=(\d+)/)[1];
  for (const theme of themeIds) {
    const frame = path.join(FRAMES, `check-${comp}-${theme}.html`);
    writeFileSync(frame, frameDocument({ base: '../project', theme, scheme: theme, libraries: index.libraries, preview: read(p) }));
    const { page, errors, blocked } = await load(browser, frame, 'light', { offline: true });
    await page.setViewportSize({ width: 960, height: 900 });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(150);
    const r = await page.evaluate(ns => {
      const shown = [...document.body.querySelectorAll('*')].filter(e => { const b = e.getBoundingClientRect(); return b.width > 0 && b.height > 0 && getComputedStyle(e).visibility !== 'hidden'; });
      const fam = f => f.family.replace(/["']/g, '');
      return {
        api: typeof window[ns] === 'object' && typeof window[ns].draw === 'function',
        text: document.body.innerText.trim().length, shapes: shown.filter(e => e.matches('svg, img, rect')).length,
        charts: document.querySelectorAll('.cm-chart').length, drawn: document.querySelectorAll('.cm-chart svg').length,
        diagrams: document.querySelectorAll('.cm-diagram').length,
        sketched: [...document.querySelectorAll('.cm-diagram')].filter(d => d.querySelector('.cm-diagram__lines') && d.querySelector('.cm-diagram__edge')).length,
        height: Math.ceil(document.body.getBoundingClientRect().height),
        nunito: [...document.fonts].some(f => fam(f) === 'Nunito' && f.status === 'loaded'),
        body: getComputedStyle(document.body).fontFamily.split(',')[0].replace(/["']/g, '').trim(),
      };
    }, index.namespace);
    render.push([
      ...errors.map(e => `${comp} ${theme}: ${e}`),
      ...[...new Set(blocked)].map(u => `${comp} ${theme}: requested ${u}`),
      !r.api && `${comp} ${theme}: window.${index.namespace} is not the kit's API`,
      !r.text && !r.shapes && `${comp} ${theme}: blank`,
      r.drawn < r.charts && `${comp} ${theme}: ${r.drawn} of ${r.charts} charts drawn`,
      r.sketched < r.diagrams && `${comp} ${theme}: ${r.sketched} of ${r.diagrams} diagrams drawn`,
      r.height > marker && `${comp} ${theme}: ${r.height}px tall, marker says ${marker}`,
      !r.nunito && `${comp} ${theme}: no Nunito face loaded`,
      r.body !== 'Nunito' && `${comp} ${theme}: body font ${r.body}`,
    ]);
    if (SHOTS) {
      await page.evaluate(() => document.documentElement.style.setProperty('background', 'var(--cm-paper)', 'important'));
      await page.screenshot({ path: path.join(SHOTS, `${comp}-${theme}.png`), fullPage: true });
    }
    await page.close();
  }
}
await browser.close();
report(`rendered: ${previews.length} previews in ${themeIds.join(' and ')}, network shut: no error, request or blank, charts and diagrams drawn, fits its marker, Nunito loaded`, render.flat());

process.exit(failed ? 1 : 0);
